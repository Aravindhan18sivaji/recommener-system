class Recommendation:
  def __init__(self,K_train,k_top_pick,Z_user,Z_item,user_features1,item_features1):
    self.K_train = K_train
    self.k_top_pick = k_top_pick
    self.Z_user = Z_user
    self.Z_item = Z_item
    self.prediction_scores = torch.matmul(self.Z_user, self.Z_item.T)
    self.topk_values_whole, self.topk_indices_whole = torch.topk(self.prediction_scores, K_train, dim=1)
    self.user_featuresfinal = user_featuresfinal
    self.item_featuresfinal = item_featuresfinal
    self.Y_test = Y_test

  def cosine_sim(self,a, b):
    return np.dot(a, b) / (np.linalg.norm(a) * np.linalg.norm(b))

  def top_recommendation(self,user_ids):
    videos = []
    for new_user in user_ids:
      video = []
      for user in new_user:
        vid = []
        for i in self.topk_indices_whole[user]:
          video.append(self.item_featuresfinal['video_id'].iloc[int(i)])
        video.extend(vid)
      videos.append(video[:])
    return videos

  def recommendations(self,X_test):
    sim_scores = []
    for i in X_test:
        user_scores = []
        for j in self.Z_user:
            score = self.cosine_sim(i, j)
            user_scores.append(score)
        sim_scores.append(user_scores[:])
    scores = np.array(sim_scores)
    return self.return_recommendation(scores)


  def return_recommendation(self,scores):
    top_k_indices = np.argsort(scores, axis=1)[:, -k_top_pick:][:, ::-1]
    top_k_scores = np.take_along_axis(scores, top_k_indices, axis=1)
    self.top_k_scores = top_k_scores
    self.top_k_indices = top_k_indices
    return self.top_recommendation(self.top_k_indices)
