def explode_vector_columns(df):
    # Identify potential vector columns
    vector_columns = []
    for col in df.columns:
        # Check if the column contains vector-like data
        try:
            # Check if first non-null value is a vector-like object
            first_non_null = df[col].dropna().iloc[0]
            if isinstance(first_non_null, (list, np.ndarray)) or (hasattr(first_non_null, '__len__') and len(first_non_null) > 1):
                vector_columns.append(col)
        except (IndexError, TypeError):
            continue

    for col in vector_columns:
        # Get the maximum vector length
        max_length = df[col].apply(lambda x: len(x) if isinstance(x, (list, np.ndarray)) else 0).max()

        # Create new columns for each vector element
        for i in range(max_length):
            new_col_name = f'{col}_{i}'
            df[new_col_name] = df[col].apply(lambda x: x[i] if isinstance(x, (list, np.ndarray)) and i < len(x) else np.nan)

        # Drop the original vector column
        df = df.drop(columns=[col])

    return df

