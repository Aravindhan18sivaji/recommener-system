def normalize_adjacency_matrix(adj_matrix):
    """Normalizes the adjacency matrix using symmetric normalization with PyTorch tensors."""
    eps = 1e-8  # Small constant to prevent division by zero

    # Convert input to a PyTorch tensor if not already
    adj_matrix = torch.tensor(adj_matrix, dtype=torch.float32)

    # Compute degree matrices
    D_u = torch.sum(adj_matrix, dim=1)
    D_i = torch.sum(adj_matrix, dim=0)

    # Compute inverse square root with safe division
    D_u_inv_sqrt = torch.zeros_like(D_u)
    D_i_inv_sqrt = torch.zeros_like(D_i)

    mask_u = D_u > 0
    mask_i = D_i > 0

    D_u_inv_sqrt[mask_u] = 1.0 / torch.sqrt(D_u[mask_u] + eps)
    D_i_inv_sqrt[mask_i] = 1.0 / torch.sqrt(D_i[mask_i] + eps)

    # Create diagonal matrices
    D_u_inv_sqrt_diag = torch.diag(D_u_inv_sqrt)
    D_i_inv_sqrt_diag = torch.diag(D_i_inv_sqrt)

    # Normalized adjacency matrix
    A_cap = D_u_inv_sqrt_diag @ adj_matrix @ D_i_inv_sqrt_diag

    return A_cap
