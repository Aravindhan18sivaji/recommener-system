    def relu_derivative(self, relu_din):
        return torch.where(relu_din > 0, torch.tensor(1.0), torch.tensor(0.0))

    def back_propagation(self):
        for _ in range(self.n_iterations):
            self.forward_propagation()
            dL_dy_cap = (2 * (self.Y - self.y_cap)) / self.n_records
            dy_cap_dreluH2 = self.W3
            dreluH2_dH2 = self.relu_derivative(self.H2)
            dH2_dreluH1 = self.W2
            dreluH1_dH1 = self.relu_derivative(self.H1)
            dH1_dW1 = self.X
            dL_dW1 = (self.X.T @ ((((dL_dy_cap @ dy_cap_dreluH2.T) * dreluH2_dH2) @ dH2_dreluH1.T) * dreluH1_dH1)) / self.n_records
            dH2_dW2 = self.relu_H1
            dL_dW2 = dH2_dW2.T @ ((dL_dy_cap @ dy_cap_dreluH2.T) * dreluH2_dH2)
            dy_cap_dW3 = self.relu_H2
            dL_dW3 = dy_cap_dW3.T @ dL_dy_cap

            # Update weights using custom AdamW
            self.update_weights(dL_dW1, dL_dW2, dL_dW3)

    def update_weights(self, dL_dW1, dL_dW2, dL_dW3):
        # Adaptive AdamW-style update with gradient normalization
        def normalize_gradient(grad):
            grad_norm = torch.norm(grad)
            return grad / grad_norm if grad_norm > 0 else grad

        # Step parameters
        beta1, beta2 = 0.9, 0.999
        eps = 1e-8
        weight_decay = 0.01

        # Increment time step
        self.t += 1

        # Normalize gradients
        dL_dW1 = normalize_gradient(dL_dW1)
        dL_dW2 = normalize_gradient(dL_dW2)
        dL_dW3 = normalize_gradient(dL_dW3)

        # AdamW-style update for W1
        self.m1 = beta1 * self.m1 + (1 - beta1) * dL_dW1
        self.v1 = beta2 * self.v1 + (1 - beta2) * (dL_dW1 ** 2)
        m1_hat = self.m1 / (1 - beta1 ** self.t)
        v1_hat = self.v1 / (1 - beta2 ** self.t)

        # AdamW-style update for W2
        self.m2 = beta1 * self.m2 + (1 - beta1) * dL_dW2
        self.v2 = beta2 * self.v2 + (1 - beta2) * (dL_dW2 ** 2)
        m2_hat = self.m2 / (1 - beta1 ** self.t)
        v2_hat = self.v2 / (1 - beta2 ** self.t)

        # AdamW-style update for W3
        self.m3 = beta1 * self.m3 + (1 - beta1) * dL_dW3
        self.v3 = beta2 * self.v3 + (1 - beta2) * (dL_dW3 ** 2)
        m3_hat = self.m3 / (1 - beta1 ** self.t)
        v3_hat = self.v3 / (1 - beta2 ** self.t)

        self.W1 = self.W1 + self.learning_rate * (m1_hat / (torch.sqrt(v1_hat) + eps) + weight_decay * self.W1)
        self.W2 = self.W2 + self.learning_rate * (m2_hat / (torch.sqrt(v2_hat) + eps) + weight_decay * self.W2)
        self.W3 = self.W3 + self.learning_rate * (m3_hat / (torch.sqrt(v3_hat) + eps) + weight_decay * self.W3)


    def return_embedding(self):
        return [self.X.numpy(), self.relu_H1.detach().numpy(), self.relu_H2.detach().numpy()]

